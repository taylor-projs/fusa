#!/usr/bin/env python3
"""Build reset_checker structural-only urg exclusions from the current VDB.

Run in sim/ after urg_report and full_exclusion dumps for tgl/line/cond/branch.
Any unclassified raw toggle hole is fatal: stimulus must be added instead.
"""
import re

METRICS = ("tgl", "line", "cond", "branch")


def parse_dump(path):
    out = {}
    cur = None
    checksum = None
    for raw in open(path, encoding="utf-8", errors="replace"):
        line = raw.rstrip("\n")
        m = re.match(r"^// CHECKSUM: (.*)$", line)
        if m:
            checksum = m.group(1)
            continue
        m = re.match(r"^// (INSTANCE|MODULE): (.*)$", line)
        if m:
            cur = "%s: %s" % (m.group(1), m.group(2))
            out[cur] = {"checksum": checksum, "rows": []}
            continue
        if cur and line.startswith("// "):
            row = line[3:]
            if row.startswith(("Toggle ", "Block ", "Branch ", "Condition ")):
                out[cur]["rows"].append(row)
    return out


DUMPS = {}
for metric in METRICS:
    DUMPS[metric] = {}
    DUMPS[metric].update(parse_dump("fullexclude." + metric))
    DUMPS[metric].update(parse_dump("fullexclude_module." + metric))


def scope_key(metric, canonical):
    candidates = (canonical, canonical + " ", canonical.rstrip())
    for key in candidates:
        if key in DUMPS[metric]:
            return key
    matches = [key for key in DUMPS[metric] if key.rstrip() == canonical.rstrip()]
    if len(matches) == 1:
        return matches[0]
    raise KeyError("scope not found for %s: %s" % (metric, canonical))


TOP_RESERVED = {"[15:10]", "[21:18]", "[24:23]", "[27:26]", "[29]", "[31]"}
CTRL_BIT3 = {"rdata[3]", "r.data_q[3]", "rin.data_q[3]"}


def split_sig(sig):
    m = re.match(r"^([\w.]+)(\[[0-9:]+\])?$", sig)
    if not m:
        return None, None
    return m.group(1), m.group(2) or ""


def toggle_family(scope, sig):
    name = scope.split(": ", 1)[1]
    base, bits = split_sig(sig)
    if name in ("reset_checker_top", "tb_reset_checker.dut"):
        if sig == "addr[1:0]":
            return "word-aligned mbus address low bits"
        if base == "rdata" and bits in TOP_RESERVED:
            return "read-mux reserved/ID-constant zero bits"
    if name in ("reset_checker_regfile",
                "tb_reset_checker.dut.u_reset_checker_regfile"):
        if sig in ("addr[1:0]", "offset[1:0]"):
            return "word-aligned mbus address low bits"
        if base in ("rdata", "rdata_mux") and bits in TOP_RESERVED:
            return "read-mux reserved/ID-constant zero bits"
        if sig == "ctrl_r[3]":
            return "CTRL legal one-hot codes never store bit3"
    if name.startswith("reg_wrap ( parameter W=4,RESET=1") or name.endswith(".u_ctrl"):
        if sig in CTRL_BIT3:
            return "CTRL legal one-hot codes never store bit3"
    if (name.startswith("reg_wrap ( parameter W=3,RESET=0")
            or name.startswith("reg_wrap ( parameter W=11,RESET=0")
            or name.endswith(".u_evimg") or name.endswith(".u_statimg")):
        if sig == "wr":
            return "follow-image reg_wrap wr tied to 1'b1"
    return None


def raw_toggle_holes(path):
    holes = {}
    scope = None
    for raw in open(path, encoding="utf-8", errors="replace"):
        line = raw.rstrip("\n")
        m = re.match(r"^Toggle Coverage for (Instance|Module) : (.*)$", line)
        if m:
            name = re.sub(r"\s*\(x\)\s*$", "", m.group(2).strip())
            scope = ("INSTANCE: " if m.group(1) == "Instance" else "MODULE: ") + name
            continue
        m = re.match(r"^\s*(\S+?)\s+(Yes|No)\s+(Yes|No)\s+(Yes|No)"
                     r"(?:\s+(INPUT|OUTPUT|INOUT))?\s*$", line)
        if scope and m and "No" in (m.group(2), m.group(3), m.group(4)):
            sig = m.group(1)
            family = toggle_family(scope, sig)
            if family is None:
                raise SystemExit("UNCLASSIFIED raw toggle hole: %s :: %s" % (scope, sig))
            actual = scope_key("tgl", scope)
            holes.setdefault(actual, set()).add(sig)
    return holes


def toggle_row(scope, sig):
    base, bits = split_sig(sig)
    rows = DUMPS["tgl"][scope]["rows"]
    declaration = None
    for row in rows:
        m = re.match(r'^Toggle (\S+) "(.*)"$', row)
        if m and m.group(1).split("[", 1)[0] == base:
            declaration = m.group(2)
            break
    if declaration is None:
        raise SystemExit("toggle declaration missing: %s :: %s" % (scope, sig))
    return 'Toggle %s%s "%s"' % (base, ((" " + bits) if bits else ""), declaration)


def write_tgl(holes):
    with open("tgl_struct_excl.el", "w", encoding="utf-8") as f:
        f.write("""// reset_checker structural-only toggle exclusions (generated by gen_rc_excl.py)
// Families:
// 1. addr/offset[1:0]: upstream mbus bridge guarantees 32-bit alignment.
// 2. rdata/rdata_mux reserved + ID-zero ranges: every register field is narrower;
//    these bits are tied to zero by the read mux, not stimulus gaps.
// 3. ctrl_r/u_ctrl data bit3: only 0001/0010/0100 pass mode_ok, so bit3 cannot store 1.
// 4. u_evimg/u_statimg wr: follow-image wrappers have wr hardwired to 1'b1.
// No duplicate-rail, value-domain, or otherwise stimulus-reachable item is excluded.
// Both INSTANCE and parameterized MODULE views are emitted from actual raw holes.
""")
        for scope in sorted(holes):
            f.write("\nCHECKSUM: %s\n%s\n" % (DUMPS["tgl"][scope]["checksum"], scope))
            for sig in sorted(holes[scope]):
                f.write(toggle_row(scope, sig) + "\n")


MISC = []


def select(metric, canonical, predicate, description):
    scope = scope_key(metric, canonical)
    rows = [row for row in DUMPS[metric][scope]["rows"] if predicate(row)]
    if len(rows) != 1:
        raise SystemExit("%s: expected one row for %s, got %r" %
                         (description, canonical, rows))
    MISC.append((metric, scope, rows[0], description))


CORE = "INSTANCE: tb_reset_checker.dut.u_reset_checker_core"
CORE_MOD = "MODULE: reset_checker_core"
for scope in (CORE, CORE_MOD):
    for vector in ("010", "100"):
        select("cond", scope,
               lambda row, v=vector: ("(sat_a | sat_b | cnt_dup) 1 -1" in row
                                      and row.endswith('"%s")' % v)),
               "single-rail saturation implies cnt_dup=1")

LINE_PLAN = (
    ("INSTANCE: tb_reset_checker.dut.u_reset_checker_regfile.u_ctrl", (3,)),
    ("INSTANCE: tb_reset_checker.dut.u_reset_checker_regfile.u_w_cmd", (3,)),
    ("INSTANCE: tb_reset_checker.dut.u_reset_checker_regfile.u_evimg", (5, 6)),
    ("INSTANCE: tb_reset_checker.dut.u_reset_checker_regfile.u_statimg", (5, 6)),
    ("MODULE: reg_wrap ( parameter W=4,RESET=1 )", (3,)),
    ("MODULE: reg_wrap ( parameter W=1,RESET=0 )", (3,)),
    ("MODULE: reg_wrap ( parameter W=3,RESET=0 )", (5, 6)),
    ("MODULE: reg_wrap ( parameter W=11,RESET=0 )", (5, 6)),
)
for scope, blocks in LINE_PLAN:
    for block in blocks:
        select("line", scope, lambda row, b=block: row.startswith("Block %d " % b),
               "mutually exclusive wr/selftest parent controls")

BRANCH_PLAN = (
    ("INSTANCE: tb_reset_checker.dut.u_reset_checker_regfile.u_ctrl", (0,)),
    ("INSTANCE: tb_reset_checker.dut.u_reset_checker_regfile.u_w_cmd", (0,)),
    ("INSTANCE: tb_reset_checker.dut.u_reset_checker_regfile.u_evimg", (2, 3)),
    ("INSTANCE: tb_reset_checker.dut.u_reset_checker_regfile.u_statimg", (2, 3)),
)
for scope, vectors in BRANCH_PLAN:
    for vector in vectors:
        select("branch", scope,
               lambda row, v=vector: row.startswith("Branch 0 ") and ("(%d)" % v) in row,
               "unreachable wr/selftest branch combination")


with open("misc_struct_excl.el", "w", encoding="utf-8") as f:
    f.write("""// reset_checker structural-only line/cond/branch exclusions (gen_rc_excl.py)
// Families:
// 1. u_ctrl/u_w_cmd Block3 + wr branch(1,1,-): wr and selftest are driven from
//    mutually exclusive register offsets (or par_bad), so wr&&selftest cannot occur.
// 2. u_evimg/u_statimg Block5/6 + wr branches(0,-,1)/(0,-,0): wr is tied high.
// 3. filt_fire subexpression vectors 010/100: if exactly one of sat_a/sat_b is 1,
//    the two counter copies necessarily disagree, hence cnt_dup=1. 100/010 are
//    Boolean impossibilities, not missing test stimulus.
""")
    last = None
    for metric, scope, row, description in MISC:
        key = (metric, scope)
        if key != last:
            f.write("\n// %s\nCHECKSUM: %s\n%s\n" %
                    (description, DUMPS[metric][scope]["checksum"], scope))
            last = key
        f.write(row + "\n")

holes = raw_toggle_holes("urg_report/modinfo.txt")
write_tgl(holes)
print("toggle scopes: %d; misc exclusion rows: %d" % (len(holes), len(MISC)))
