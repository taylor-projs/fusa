#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
rdl2def.py -- SystemRDL -> register define files for C / Verilog consumers.

Faithful port of reg_gen_parity.pl (v0p3-2023/4/5) Gen_def_file +
Gen_bdef_file, i.e. the perl's `--def` option.  Reads the same RDL as
rdl2reg.py and emits three sibling files named after the addrmap (module):

    <module>_define.v       `define OFST_<MODULE>_<REG> (32'h%04x) macros
    <module>_define.h       #define OFST_<MODULE>_<REG> (0x%04x) macros
    <module>_bit_define.h   per-register OFST / MASK / DFLT macros plus
                            per-field BIT_* / ATTR_* macros

Byte-identical to the perl's --def output modulo the Date/User header line
(the ONLY intentional divergence: DFLT_ macros on maps whose reserved cells
hold a bare `0` -- the perl reuses a stale radix there, we emit the clean
value; see SPEC.md §11).

Usage:
    python3 rdl2def.py <in.rdl> [-o outdir] [--date s] [--user s]
"""

import os
import re
import subprocess
import sys
from datetime import datetime

import rdl2reg
import regmodel

SEP = "//" + "-" * 49 + "\n"   # perl 49-dash section separator
DOTS = "//" + "." * 31 + "\n"  # perl 31-dot register separator

COPY_DEF = (
    "/*\n * Horizon Robotics\n *\n * Copyright (C) 2022 Horizon Robotics "
    "Inc.\n * All rights reserved.\n *\n * This file is auto generated by "
    "Horizon Robotics for Sigiriya Chip.\n"
    " * Version :J6B-fusa update \n * %s %s*/")

COPY_BDEF = (
    "/*\n * Horizon Robotics\n *\n * Copyright (C) 2022 Horizon Robotics "
    "Inc.\n * All rights reserved.\n *\n * This file is auto generated by "
    "Horizon Robotics for Sigiriya Chip.\n"
    " * Version: J6B-fusa update\n * %s %s*/")


def module_upper(mod):
    """uc($moduleName) with the perl's clk_rf name special cases."""
    mu = mod.name.upper()
    if re.search(r"[a-zA-Z0-9]_pre_div_clk_rf", mod.name):
        mu = mu.replace("_CLK_RF", "_CLK")
    elif re.search(r"[a-zA-Z0-9]_clk_rf", mod.name):
        mu = mu.replace("_CLK_RF", "_CLKTOP")
    return mu


def gen_def_file(mod, date_str, user_str):
    """Gen_def_file -> (<module>_define.v, <module>_define.h) texts."""
    mu = module_upper(mod)
    v = [COPY_DEF % (date_str, user_str)]
    h = [COPY_DEF % (date_str, user_str)]
    v.append("\n`ifndef %s_DEF_V_" % mu)
    v.append("\n`define %s_DEF_V_\n" % mu)
    v.append("//\n")
    v.append("//Register offset macro defines\n")
    v.append("//\n")
    h.append("\n#ifndef %s_DEF_H_" % mu)
    h.append("\n#define %s_DEF_H_\n" % mu)
    h.append("//\n")
    h.append("//Register offset macro defines\n")
    h.append("//\n")
    for reg in mod.regs:
        mac = "OFST_%s_%s" % (mu, reg.gname_uc)
        v.append("`define %-40s  (32'h%04x)\n" % (mac, reg.offset_int))
        h.append("#define %-40s  (0x%04x)\n" % (mac, reg.offset_int))
    v.append("\n`endif //%s_DEF_V_\n" % mu)
    h.append("\n#endif //%s_DEF_H_\n" % mu)
    return "".join(v), "".join(h)


def _bit_or(msb, lsb):
    """perl $bit_or: '()' then s/\\)/|BIT_%-2d)/g per k=lsb..msb, s/(|/(/."""
    bit_or = "()"
    for k in range(lsb, msb + 1):
        bit_or = bit_or.replace(")", "|BIT_%-2d)" % k)
    return bit_or.replace("(|", "(")


def gen_bdef_file(mod, date_str, user_str):
    """Gen_bdef_file -> <module>_bit_define.h text."""
    mu = module_upper(mod)
    o = [COPY_BDEF % (date_str, user_str)]
    o.append("\n#ifndef %s_DEF_H_" % mu)
    o.append("\n#define %s_DEF_H_\n" % mu)
    o.append("//\n")
    o.append("//\n")
    o.append("//Register macro defines\n")
    o.append("//\n")

    # ---- OFST ----
    o.append("\n\n")
    o.append(SEP)
    o.append("//Register offset macro defines\n")
    o.append(SEP)
    for reg in mod.regs:
        o.append("#define %-40s  (0x%04x)\n"
                 % ("OFST_%s_%s" % (mu, reg.gname_uc), reg.offset_int))

    # ---- MASK (reg_mask: 1s on sw-writable non-reserved bits) ----
    o.append("\n\n")
    o.append(SEP)
    o.append("//Register mask macro defines\n")
    o.append(SEP)
    for reg in mod.regs:
        o.append("#define %-40s  (%-10s)\n"
                 % ("MASK_%s_%s" % (mu, reg.gname_uc),
                    "0x" + reg.reg_mask_hex))

    # ---- DFLT (reg_value: concatenated reset values) ----
    o.append("\n\n")
    o.append(SEP)
    o.append("//Register default value macro defines\n")
    o.append(SEP)
    for reg in mod.regs:
        o.append("#define %-40s  (%-10s)\n"
                 % ("DFLT_%s_%s" % (mu, reg.gname_uc),
                    "0x" + reg.reg_value_hex))

    # ---- per-register bit information ----
    o.append("\n\n")
    o.append(SEP)
    o.append(SEP)
    o.append("//Register bit information\n")
    o.append(SEP)
    o.append(SEP)
    for reg in mod.regs:
        reg_name = "OFST_%s_%s" % (mu, reg.gname_uc)
        o.append("\n" + DOTS)
        o.append("//Register Name: %s\n" % reg_name)
        o.append("//Register offset: 0x%x\n" % reg.offset_int)
        o.append(DOTS)
        for f in reg.fields:
            if f.msb == 31 and f.lsb == 0:
                o.append("\n")            # full-width field: no macros
                continue
            if f.rname == "reserved":     # perl: literal 'reserved' only
                continue                  # (rname folds the RDL dedup
                                           #  reserved_1..N back to reserved)
            fun = f.name.upper()
            if f.width == 1:
                o.append("#define %-50s  (BIT_%d)\n"
                         % ("BIT_%s_%s_%s" % (mu, reg.gname_uc, fun), f.msb))
            else:
                o.append("#define %-50s  ((_X_) << %-2d & %s)\n"
                         % ("BIT_%s_%s_%s(_X_)" % (mu, reg.gname_uc, fun),
                            f.lsb, _bit_or(f.msb, f.lsb)))
            o.append("#define %-50s  (ATTR_%s)\n"
                     % ("ATTR_%s_%s_%s" % (mu, reg.gname_uc, fun),
                        f.attr.upper()))
    o.append("\n#endif //%s_DEF_H_\n" % mu)
    return "".join(o)


def generate(mod, date_str, user_str):
    """-> [(filename, text)] for the three define files."""
    rdl2reg.reg_value_loop2(mod)   # fills reg.reg_mask_hex / reg.reg_value_hex
    v, h = gen_def_file(mod, date_str, user_str)
    b = gen_bdef_file(mod, date_str, user_str)
    return [("%s_define.v" % mod.name, v),
            ("%s_define.h" % mod.name, h),
            ("%s_bit_define.h" % mod.name, b)]


def main():
    args = sys.argv[1:]
    infile = None
    outdir = None
    date_str = None
    user_str = None
    usage = ("usage: rdl2def.py <in.rdl> [-o outdir] "
             "[--date s] [--user s]\n")
    i = 0
    while i < len(args):
        a = args[i]
        if a == "-o":
            if i + 1 >= len(args):
                sys.stderr.write(usage)
                sys.exit(1)
            outdir = args[i + 1]
            i += 2
        elif a == "--date":
            date_str = args[i + 1]
            i += 2
        elif a == "--user":
            user_str = args[i + 1]
            i += 2
        else:
            if infile is not None:
                sys.stderr.write(usage)
                sys.exit(1)
            infile = a
            i += 1
    if infile is None:
        sys.stderr.write(usage)
        sys.exit(1)
    if date_str is None:
        date_str = datetime.now().strftime("Date : %Y-%m-%d %H:%M:%S")
    if user_str is None:
        try:
            user_str = subprocess.check_output(["whoami"]).decode().strip()
        except Exception:
            user_str = "unknown"

    print("\n[INFO]: input rdl file is  %s" % infile)
    try:
        mod = rdl2reg.parse_rdl(infile)
        files = generate(mod, date_str, user_str)
    except regmodel.RdlError as e:
        sys.stderr.write("[ERROR] %s\n" % e)
        sys.exit(1)
    for name, text in files:
        path = os.path.join(outdir, name) if outdir else name
        with open(path, "w") as fh:
            fh.write(text)
        print("[INFO]: wrote %s (%d bytes)" % (path, len(text)))
    print("[INFO]: Generation DONE")


if __name__ == "__main__":
    main()
